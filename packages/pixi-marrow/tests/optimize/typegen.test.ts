import { describe, expect, it } from 'vitest';
import { MarrowError } from '../../src/base/errors';
import type { SkeletonInfo } from '../../src/model/info';
import { generateNames, typeNameFor } from '../../src/optimize/typegen';

const info: SkeletonInfo = {
    version: '4.3',
    editorVersion: '4.3.13',
    bones: ['root', 'front "arm"'],
    slots: ['body'],
    skins: ['default', 'armor'],
    events: [],
    constraints: [],
    animations: [
        { name: 'idle', duration: 1, timelines: 1, features: [] },
        { name: 'run', duration: 1, timelines: 1, features: [] },
    ],
    counts: {
        bones: 2,
        slots: 1,
        skins: 2,
        constraints: 0,
        animations: 2,
        attachments: 0,
        regions: 0,
        meshes: 0,
        meshVertices: 0,
        maxBonesPerVertex: 0,
    },
    features: [],
};

describe('generateNames', () => {
    it('writes one type with a union per kind of name', () => {
        expect(generateNames(info, { typeName: 'HeroNames', source: 'hero.skel' })).toBe(
            [
                '// Generated by pixi-marrow typegen from hero.skel. Do not edit.',
                '',
                '/** Every name in the skeleton (Spine 4.3.13). */',
                'export type HeroNames = {',
                '    animations: "idle" | "run";',
                '    skins: "default" | "armor";',
                '    bones: "root" | "front \\"arm\\"";',
                '    slots: "body";',
                '    events: never;',
                '};',
                '',
            ].join('\n'),
        );
    });

    it('leaves the source out of the header when none is given', () => {
        expect(generateNames(info, { typeName: 'N' }).split('\n')[0]).toBe(
            '// Generated by pixi-marrow typegen. Do not edit.',
        );
    });

    it('rejects a type name that is not an identifier', () => {
        for (const typeName of ['', '9Lives', 'Hero Names', 'a-b']) {
            expect(() => generateNames(info, { typeName })).toThrow(MarrowError);
        }
    });
});

describe('typeNameFor', () => {
    it('builds a type name from a file name', () => {
        expect(typeNameFor('hero-pro.skel')).toBe('HeroProNames');
        expect(typeNameFor('assets/spine/mix-and-match.json')).toBe('MixAndMatchNames');
        expect(typeNameFor('C:\\art\\coin.skel')).toBe('CoinNames');
        expect(typeNameFor('1-weight-and-mass.skel')).toBe('Skeleton1WeightAndMassNames');
        expect(typeNameFor('.skel')).toBe('SkeletonNames');
    });
});
